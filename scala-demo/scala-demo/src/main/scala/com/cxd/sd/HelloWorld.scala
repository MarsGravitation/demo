package com.cxd.sd

/**
 * main 方法名
 * 小括号表示参数列表
 *  参数声明方式：参数名 : 类型
 *
 * public: scala 没有 public 关键字，如果不声明访问权限，那么就是公共的。
 * static: scala 中没有静态语法，所以没有 static 关键字
 * void: 表示返回值，但是遵循面向对象语法，所以 scala 中没有，但是有 Unit 类型，表示没有返回值
 * scala 中：方法名（参数列表）：返回值类型
 * scala 中声明方法必须采用关键字 def 声明
 * scala 中方法实现赋值给方法声明，所以中间需要等号连接
 *
 * scala 完全米娜想对象，故 scala 去掉了 Java 中非面向对象的元素：如 static，void 类型
 *  - scala 无 static 关键字，有 object 实现类似静态方法的功能（类名.方法名）
 *
 * void
 *  对于无返回值的函数，scala 定义其返回值类型为 Unit 类
 *
 * 2.2 变量和常量
 *  var 变量名[:变量类型] = 初始值
 *  val 长联名[:常量类型] = 初始值
 *  注意：能用常量的地方不用变量
 *
 *  - 声明变量时，类型可以省略，编译器自动推到，即类型推导
 *  - 类型确定后，就不能修改，说明 scala 是强类型语言
 *  - 类型声明时，必须要有初始值
 *  - 在声明/定义一个变量时，可以使用 var 或 val 来修饰，var 修饰的变量可改变，val 修改时的变量不可改变
 *  - var 修饰的对象引用可以改变，val 修饰的对象则不可改变，但对象的值确实可以改变的。
 *
 * 2.4 字符串输出
 *  1. 字符串，通过 + 号连接
 *  2. printf 通过 % 传值
 *  3. 字符串模板：通过 $ 获取变量值
 *
 * 2.6 数据类型
 *  1. scala 中一切数据都是对象，都是 Any 的子类
 *  2. scala 数据类型分为两大类，数值类型，引用类型，不管是值类型还是引用类型都是对象
 *  3. scala 数据类型仍遵守，低精度的值类型想高精度类型，自动转换
 *  4. scala 中的 StringOps 是对 Java 中的 String 增强
 *  5. Unit 对应 Java 中的 void，用于方法的返回值的位置，表示方法没有返回值。
 *  Unit 是一个数据类型，只有一个对象就是 ()。void 不是数据类型，只是一个关键字
 *  6. Null 是一个类型，只有一个对象就是 null，它是所有引用类型的子类。
 *  7. Nothing 是所有数据类型的子类，主要用在一个函数没有明确返回值时使用，因为
 *  这样我们可以把抛出的返回值，返回给任何变量或函数
 *
 * 2.7 整数类型
 * 2.8 浮点类型
 * 2.9 字符类型
 * 2.10 布尔类型
 * 2.11 Unit类型，Null 类型和 Nothing 类型
 *  1. Unit 类型用来标识过程，也就是没有明确返回值的函数
 *  2. Null 类只有一个实例对象，Null 可以赋值给任意应用类型，但是不能赋值给值类型
 *  3. Nothing 可以作为没有正常返回值的方法的放回类型，非常直观的告诉你这个方法
 *  不会正常返回，而且由于 Nothing 是其他任意类型子类，他还能要求返回值的方法兼容
 *
 * 2.12. 类型转换
 *
 * 3. 运算符
 * 4. 流程控制
 * 4.1 分支控制 if-else
 *
 */
object HelloWorld {
  def main(args: Array[String]): Unit = {
    println("hello world")
  }
}
